import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

/** Writes results/SUMMARY.md from the raw results of run.mjs. */
const results = join(dirname(fileURLToPath(import.meta.url)), 'results')
const yes = value => value ? 'equal' : '**differs**'
const lines = ['# Holdout replay summary', '', 'Generated by `summarize.mjs` from the JSON files in this directory.', '']

for (const file of readdirSync(results).filter(name => /^[^.]+\.json$/.test(name)).sort()) {
  const result = JSON.parse(readFileSync(join(results, file), 'utf8'))
  const hosts = result.revisions[0].hostInfo
  lines.push(
    `## ${result.subject}`,
    '',
    `Project \`${result.project}\` of \`${result.config}\`, FASTER commit \`${result.faster.slice(0, 12)}\`, Node ${result.node}.`,
    `The fork (Vitest ${hosts.fork.vitest}) orders with \`${hosts.fork.sequencer}\`; the plugin host (Vitest ${hosts.plugin.vitest}) orders with \`${hosts.plugin.sequencer}\`.`,
    '',
    '| Revision | Role | Files | Selected (fork / plugin) | Selected set | Selected order (shared durations) | Full order (own durations) | Full order (shared durations) | Duration-rank inversions | Per-file outcomes | Persisted state |',
    '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |',
  )
  for (const revision of result.revisions) {
    const comparison = revision.comparison
    // When the fork's configuration bypassed FasterSequencer, compare with the
    // order FasterSequencer computes; the as-configured result is listed below.
    const ordering = comparison.forkFasterSequencer ?? comparison
    const shared = ordering.sharedDurations
    const sharedEqual = part => shared.forkHistory[part].equal && shared.pluginHistory[part].equal
    const ranks = comparison.history.durationRanks
    lines.push(`| \`${revision.revision.slice(0, 8)}\` | ${revision.role} | ${revision.hostInfo.fork.files} | ${comparison.selectedSet.fork} / ${comparison.selectedSet.plugin} | ${yes(comparison.selectedSet.equal)} | ${yes(sharedEqual('selectedOrder'))} | ${ordering.fullOrder.equal ? 'equal' : `differs at ${ordering.fullOrder.differingPositions} positions`} | ${yes(sharedEqual('fullOrder'))} | ${ranks.pairs ? `${ranks.inversions} of ${ranks.pairs} pairs` : 'no history'} | ${yes(comparison.outcomes.equal)} | ${yes(revision.persistedState.equal)} |`)
  }
  if (result.revisions.some(revision => revision.comparison.forkFasterSequencer)) {
    lines.push(
      '',
      'The fork\'s configured sequencer is not `FasterSequencer` here. The subject\'s config sets `test.sequence`, and the fork then keeps `BaseSequencer` (see README). The order columns above compare the plugin with the fork\'s `FasterSequencer`. Against the order the fork actually used:',
      '',
      '| Revision | Full order | Selected order |',
      '| --- | --- | --- |',
      ...result.revisions.map(revision => `| \`${revision.revision.slice(0, 8)}\` | ${revision.comparison.fullOrder.equal ? 'equal' : `differs at ${revision.comparison.fullOrder.differingPositions} positions`} | ${revision.comparison.selectedOrder.equal ? 'equal' : `differs at ${revision.comparison.selectedOrder.differingPositions} positions`} |`),
    )
  }
  lines.push('', '| Revision | Fork run (s) | Plugin run (s) | Fork exit | Plugin exit | Tests (passed/failed/skipped) |', '| --- | --- | --- | --- | --- | --- |')
  for (const revision of result.revisions) {
    const { fork, plugin } = revision.runs
    lines.push(`| \`${revision.revision.slice(0, 8)}\` | ${(fork.wallMs / 1000).toFixed(1)} | ${(plugin.wallMs / 1000).toFixed(1)} | ${fork.exitCode} | ${plugin.exitCode} | ${fork.outcomes.passed}/${fork.outcomes.failed}/${fork.outcomes.skipped} |`)
  }
  if (result.timing) {
    const { summary, pluginOverFork, fasterOverhead, repetitions } = result.timing
    lines.push(
      '',
      `Timing at the last revision, ${repetitions} interleaved full runs per configuration (median wall time, min–max):`,
      '',
      '| Configuration | Median (s) | Min (s) | Max (s) |',
      '| --- | --- | --- | --- |',
      ...Object.entries(summary).map(([key, value]) => `| ${key} | ${(value.medianMs / 1000).toFixed(1)} | ${(value.minMs / 1000).toFixed(1)} | ${(value.maxMs / 1000).toFixed(1)} |`),
      '',
      `Plugin / fork with FASTER on: ${pluginOverFork.toFixed(3)}. FASTER on / off: fork ${fasterOverhead.fork.toFixed(3)}, plugin ${fasterOverhead.plugin.toFixed(3)}.`,
    )
  }
  const determinism = join(results, `${result.subject}.determinism.json`)
  if (existsSync(determinism)) {
    const repeat = JSON.parse(readFileSync(determinism, 'utf8'))
    const tests = pairs => [...new Set(pairs.flatMap(pair => Object.keys(pair.differingTests)))]
    lines.push(
      '',
      `Repeated full runs at the last revision (\`determinism.mjs\`, ${repeat.repeats} per host). Tests whose recorded function observations differ:`,
      '',
      `- between runs of the fork: ${tests(repeat.withinHost.fork).map(test => `\`${test}\``).join(', ') || 'none'}`,
      `- between runs of the plugin: ${tests(repeat.withinHost.plugin).map(test => `\`${test}\``).join(', ') || 'none'}`,
      `- between the fork and the plugin in the same round: ${tests(repeat.acrossHosts).map(test => `\`${test}\``).join(', ') || 'none'}`,
      `- per-file outcomes equal across hosts in every round: ${repeat.outcomesEqual.every(Boolean) ? 'yes' : 'no'}`,
    )
  }
  const small = join(results, `${result.subject}.small-runs.json`)
  if (existsSync(small)) {
    const report = JSON.parse(readFileSync(small, 'utf8'))
    lines.push(
      '',
      `Small runs at the last revision (\`small-runs.mjs\`, ${report.repeats} interleaved runs per host, FASTER on, median wall time):`,
      '',
      '| Files | Fork (s) | Plugin (s) | Plugin / fork |',
      '| --- | --- | --- | --- |',
      ...Object.values(report.runs).map(run => `| ${run.files} | ${(run.medianMs.fork / 1000).toFixed(2)} | ${(run.medianMs.plugin / 1000).toFixed(2)} | ${run.pluginOverFork.toFixed(3)} |`),
    )
  }
  const overhead = join(results, `${result.subject}.overhead.json`)
  if (existsSync(overhead)) {
    const report = JSON.parse(readFileSync(overhead, 'utf8'))
    const seconds = value => `${value >= 0 ? '+' : ''}${(value / 1000).toFixed(2)}`
    lines.push(
      '',
      `One-file run \`${report.file}\` (\`overhead.mjs\`, ${report.rounds} interleaved runs per host and configuration). Plugin minus fork, median wall time (s):`,
      '',
      '| FASTER on | on, `changed: false` | off |',
      '| --- | --- | --- |',
      `| ${seconds(report.pluginMinusForkMs.on)} | ${seconds(report.pluginMinusForkMs['no-change-tracking'])} | ${seconds(report.pluginMinusForkMs.off)} |`,
      '',
      `The plugin's \`sort\` of that file, which waits for the pre-run source snapshot: ${report.pluginSortWithSnapshotMs.map(value => (value / 1000).toFixed(2)).join(', ')} s.`,
    )
  }
  lines.push('')
}
writeFileSync(join(results, 'SUMMARY.md'), lines.join('\n'))
process.stdout.write(`${lines.join('\n')}\n`)
